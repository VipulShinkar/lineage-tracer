"""Evidence pack for a trace: summary, hop table with status + evidence, SQL excerpts, reconciliation results.
Reuses the existing pack renderer and storage (lineage_store.evidence / evidence_pack table)."""

from __future__ import annotations

import hashlib
import io
from datetime import datetime, timezone

from lineage_store import audit, evidence

HEAD = ["Hop", "Status", "From → To", "Transformation", "Evidence", "Reconciliation"]


def blocks(lin: dict, ref: str, viewer: str, ts: str) -> list[tuple]:
    h, s = lin["header"], lin["summary"]
    ev = lambda x: " · ".join(v for v in (x.get("code"), x.get("version"), x.get("log")) if v)  # noqa: E731
    sql = [("p", f"Hop {x['n']}: {x['evidence']['sql'][:1200]}") for x in lin["hops"] if x["evidence"].get("sql")]
    return [
        ("summary", [("h", "Lineage trace evidence pack"),
                     ("table", ["Item", "Value"], [["Reference", ref], ["Data point", h["label"]],
                                                   ["Reported value", f"{h['value']:,} {h.get('unit') or ''}".strip()],
                                                   ["Reference date", h.get("ref_date") or ""], ["Result", s["title"]],
                                                   ["Hops", f"{s['hops']} ({s['proven']} proven, {s['code_derived']} code-derived, "
                                                            f"{s['unresolved']} unresolved)"],
                                                   ["Generated by", viewer], ["Generated at", ts]])]),
        ("hops", [("h", "Hops"), ("table", HEAD, [[str(x["n"]), x["status"].replace("_", "-"), f"{x['from']} → {x['to']}",
                                                    x["transformation"], ev(x["evidence"]),
                                                    x["evidence"].get("reconciliation", "")] for x in lin["hops"]])]),
        ("sql", [("h", "SQL excerpts")] + (sql or [("p", "No SQL was captured.")])),
    ]


def build_docx(content: list[tuple], wm: str) -> bytes:
    from docx import Document

    doc = Document()
    doc.sections[0].header.paragraphs[0].text = wm
    for _, bl in content:
        for b in bl:
            if b[0] == "h":
                doc.add_heading(b[1], level=1 if b[1].startswith("Lineage") else 2)
            elif b[0] == "p":
                doc.add_paragraph(b[1])
            else:
                t = doc.add_table(rows=1, cols=len(b[1]), style="Light Grid Accent 1")
                for i, x in enumerate(b[1]):
                    t.rows[0].cells[i].text = str(x)
                for r in b[2]:
                    for i, x in enumerate(t.add_row().cells):
                        x.text = str(r[i])
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def create(conn, tid: str, lin: dict, fmt: str, actor: str = "tracer user") -> dict:
    if fmt not in ("pdf", "docx"):
        raise ValueError("format must be pdf or docx")
    n = conn.execute("SELECT nextval('evidence_pack_seq')").fetchone()[0]
    now = datetime.now(timezone.utc)
    ref = f"TRC-{(lin['header'].get('ref_date') or now.date().isoformat()).replace('-', '')}-{n:04d}"
    ts, viewer = now.strftime("%Y-%m-%d %H:%M UTC"), f"{actor} (tracer)"
    content = blocks(lin, ref, viewer, ts)
    wm = f"{ref} · {viewer} · {ts}"
    data = evidence._pdf(content, wm, ref, f"{viewer} · {ts}", "Lineage trace evidence pack") if fmt == "pdf" \
        else build_docx(content, wm)
    name = f"{ref}.{fmt}"
    (evidence.evidence_dir() / name).write_bytes(data)
    sha = hashlib.sha256(data).hexdigest()
    conn.execute("INSERT INTO evidence_pack (ref, cell, format, file_path, sha256, watermark, created_by, created_at) "
                 "VALUES (%s,%s,%s,%s,%s,%s,%s,%s)", (ref, f"trace:{tid}", fmt, name, sha, wm, actor, now))
    audit.append(conn, actor, "tracer", "generated evidence pack", f"{ref} · trace {tid}")
    return {"ref": ref, "sha256": sha, "download_url": f"/api/evidence-packs/{ref}"}
