"""Evidence pack (PDF via reportlab, DOCX via python-docx), impact report and placeholder adjustment evidence.

The content is built once as neutral blocks from a lineage snapshot payload, then rendered per format.
Every page carries a watermark: reference, viewer and time. Customer identifiers are always masked (the
snapshot payload never holds raw ones).
"""

from __future__ import annotations

import io
import os
from pathlib import Path
from xml.sax.saxutils import escape

from lineage_store import regulator

REPO = Path(__file__).resolve().parents[2]
NAVY, ORANGE, RED = "#1f3a5f", "#d9822b", "#b3261e"


def evidence_dir() -> Path:
    d = Path(os.environ.get("LINEAGE_EVIDENCE_DIR") or REPO / "output" / "evidence")
    d.mkdir(parents=True, exist_ok=True)
    return d


def _f(x, nd: int = 1) -> str:
    return f"{x:,.{nd}f}".replace("-", "−")


# ---------------------------------------------------------------- neutral content
def blocks(p: dict, sections: list[str], ref: str, viewer: str, ts: str) -> list[tuple]:
    """[(section_key, [block, ...])] where block is ('h', text) | ('p', text) | ('table', header, rows)
    | ('diagram', lineage) | ('chart', steps)."""
    h, wf = p["cell_header"], p["waterfall"]
    label = f"{h['template']} {h['row']} {h['col']}"
    out: dict[str, list] = {}
    out["cover"] = [
        ("h", "Lineage evidence pack"),
        ("table", ["Item", "Value"], [
            ["Reference", ref], ["Cell", f"{label} · {h['sheet']} · {h['row_label']}, {h['col_label']}"],
            ["Reported value", f"{_f(h['value'])} {h['unit']}"],
            ["Submission", f"{p['submission']['ref_date']} {p['submission']['version']} "
                           f"(submitted {p['submission']['submitted_on']})"],
            ["Generated by", viewer], ["Generated at", ts], ["Linked request", "[REF]"]]),
        ("h", "Sign-off"),
        ("table", ["Role", "Name", "Signature", "Date"], [
            ["Prepared by", "", "", ""], ["Reviewed by", "", "", ""], ["Approved by (Head of Reg Reporting)", "", "", ""]]),
    ]
    out["narrative"] = [
        ("h", "Plain-English narrative"), ("p", regulator.narrative(p)),
        ("table", ["Stage", "Value (EUR m)", "Note"], [[s["label"], _f(s["value"]), s["note"]] for s in regulator.stages(p)])]
    out["diagram"] = [("h", "Hop diagram"), ("diagram", p["lineage"]),
                      ("p", "Numbered circles are hops; orange = manual / EUC; dashed red = known gap.")]
    out["sourcing"] = [("h", "Sourcing at each hop"), ("table",
        ["Hop", "From → To", "Mechanism", "Cut-off / run", "Records in → out", "Value in → out"],
        [[str(x["hop"]["n"]), f"{x['hop']['from']} → {x['hop']['to']}", f"{x['hop']['mechanism']} · {x['hop']['frequency']}",
          f"{x['hop']['cutoff']} · {x['hop']['run_id']}", f"{x['records']['in']:,} → {x['records']['out']:,}",
          f"{_f(x['records']['value_in'])} → {_f(x['records']['value_out'])}"] for x in p["hops"]])]
    tr = p["transformations"]
    m = tr["mapping"]
    out["transformations"] = [("h", "Transformations with versions"), ("p", f"Versions in force on {tr['as_of']}."),
        ("table", ["ID", "Type", "Hop", "Amount", "Version", "Owner", "Reference"],
         [[t["id"], t["type"], t["hop"], _f(t["amount"]), t["version"] + (f" · eff. {t['effective_from']}" if t.get("effective_from") else ""),
           t["owner"], t["reference"]["label"]] for t in tr["transformations"]]),
        ("p", f"Mapping used by T4: {m['name']} v{m['version']} (effective {m['effective_from']})"
              + (f"; previous version {m['previous_version']} differs in {m['differs_in']} rows." if m.get("previous_version") else ".")),
        ("table", ["Code", "Product", "Exposure class"], [[r["code"], r["label"], r["target"]] for r in m["rows"]])]
    out["waterfall"] = [("h", "Value waterfall"),
        ("table", ["Step", "Detail", "Amount (EUR m)"], [[s["label"], s["sublabel"], _f(s["amount"])] for s in wf["steps"]]),
        ("p", f"Residual {_f(wf['residual'])} · tolerance ±{wf['tolerance']} · "
              f"{'within' if wf['within_tolerance'] else 'outside'} tolerance."), ("chart", wf["steps"])]
    adj = [("h", "Manual adjustments and approvals")]
    for a in p["adjustments"]:
        adj.append(("table", ["Field", a["id"]], [
            ["Amount", _f(a["amount"])], ["Description", a["description"]], ["Maker", f"{a['maker']} · {a['maker_at']}"],
            ["Checker", f"{a['checker']} · {a['checker_at']}"], ["Source", a["source"]], ["Evidence", a["evidence"]["label"]]]))
    if not p["adjustments"]:
        adj.append(("p", "No manual adjustments affect this cell."))
    out["adjustments"] = adj
    seen, ctl = set(), []
    for x in p["hops"]:
        for c in x["controls"]:
            if c["id"] not in seen:
                seen.add(c["id"])
                ctl.append([f"H{x['hop']['n']}", c["name"], c["status"].upper(), c["detail"]])
    out["controls"] = [("h", "Control results"), ("p", wf["controls"]["summary"]),
                       ("table", ["Hop", "Control", "Status", "Detail"], ctl)]
    r = p["records"]
    out["contributors"] = [("h", "Top contributors (masked)"),
        ("p", f"{r['contributing_records']:,} contributing records; drill-down total {_f(r['drilldown_total'])} = reported."),
        ("table", ["Counterparty", "Sector · product", "Source", "Source key", "Value"],
         [[t["counterparty"], t["sector_product"], t["source"], t["source_key"], _f(t["value"])] for t in r["top"]]),
        ("table", ["Sector", "Records", "Current", "Prior quarter", "Change"],
         [[g["key"], f"{g['records']:,}", _f(g["current"]), _f(g["compare"]), _f(g["change"])] for g in r["groups"]])]
    lim = regulator.limitations(p)
    out["limitations"] = [("h", "Known limitations")] + [("p", "• " + x["text"]) for x in lim] or [("p", "None.")]
    if not lim:
        out["limitations"].append(("p", "None."))
    return [(k, out[k]) for k, _ in regulator.SECTIONS if k in sections]


# ---------------------------------------------------------------- PDF
_PDF_MAP = {"−": "-", "→": "->", "≠": "!=", "÷": "/", "Σ": "Sum", "’": "'", "“": '"', "”": '"'}


def _t(s) -> str:
    s = str(s)
    for k, v in _PDF_MAP.items():
        s = s.replace(k, v)
    return s.encode("cp1252", "replace").decode("cp1252")


def _diagram(lin: dict, width: float = 510):
    from reportlab.graphics.shapes import Circle, Drawing, Line, Polygon, Rect
    from reportlab.graphics.shapes import String as _S
    from reportlab.lib import colors

    String = lambda *a, **k: _S(*a, fontName="Helvetica", **k)  # noqa: E731

    ncol, boxh = len(lin["lanes"]), 26
    colw = width / ncol
    boxw = colw - 16
    lanes: dict[int, list] = {}
    for n in lin["nodes"]:
        lanes.setdefault(n["lane"], []).append(n)
    height = max(len(v) for v in lanes.values()) * (boxh + 10) + 34
    d = Drawing(width, height)
    pos = {}
    for i, name in enumerate(lin["lanes"]):
        d.add(String(i * colw + 4, height - 10, name, fontSize=5.5, fillColor=colors.grey))
    for lane, ns in lanes.items():
        for i, n in enumerate(ns):
            x, y = lane * colw + 4, height - 24 - (i + 1) * (boxh + 10) + 10
            pos[n["uid"]] = (x, y)
            k = n["kind"]
            fill = {"manual": "#fbe3cc", "anchor": NAVY}.get(k, "#eef2f7")
            stroke = {"manual": ORANGE, "gap": RED}.get(k, NAVY)
            r = Rect(x, y, boxw, boxh, rx=3, ry=3, fillColor=colors.HexColor(fill), strokeColor=colors.HexColor(stroke),
                     strokeWidth=0.8)
            if k == "gap":
                r.strokeDashArray = [3, 2]
            d.add(r)
            tc = colors.white if k == "anchor" else colors.black
            d.add(String(x + 3, y + boxh - 8, _t(k.upper()), fontSize=4.5, fillColor=colors.grey if k != "anchor" else colors.white))
            d.add(String(x + 3, y + 5, _t(n["label"])[:22], fontSize=5, fillColor=tc))
    for e in lin["edges"]:
        (x1, y1), (x2, y2) = pos[e["src"]], pos[e["dst"]]
        sx, sy, ex, ey = x1 + boxw, y1 + boxh / 2, x2, y2 + boxh / 2
        ln = Line(sx, sy, ex, ey, strokeColor=colors.HexColor(RED if e.get("dashed") else "#777777"), strokeWidth=0.7)
        if e.get("dashed"):
            ln.strokeDashArray = [3, 2]
        d.add(ln)
        d.add(Polygon([ex, ey, ex - 4, ey + 2, ex - 4, ey - 2], fillColor=colors.HexColor("#777777"), strokeColor=None))
        if e.get("hop"):
            mx, my = (sx + ex) / 2, (sy + ey) / 2
            d.add(Circle(mx, my, 5, fillColor=colors.HexColor(NAVY), strokeColor=None))
            d.add(String(mx - 1.8, my - 2, str(e["hop"]), fontSize=6, fillColor=colors.white))
    return d


def _chart(steps: list, width: float = 510, height: float = 140):
    from reportlab.graphics.shapes import Drawing, Line, Rect
    from reportlab.graphics.shapes import String as _S
    from reportlab.lib import colors

    String = lambda *a, **k: _S(*a, fontName="Helvetica", **k)  # noqa: E731

    run, spans = 0.0, []
    for s in steps:
        if s["kind"] == "total":
            spans.append((0.0, s["amount"]))
            run = s["amount"]
        else:
            spans.append((run, run + s["amount"]))
            run += s["amount"]
    lo = int(min(min(a, b) for a, b in spans) // 100 * 100)
    hi = max(max(a, b) for a, b in spans)
    scale = (height - 40) / (hi - lo)
    d = Drawing(width, height)
    bw = width / len(steps)
    for i, (s, (a, b)) in enumerate(zip(steps, spans)):
        a = max(a, lo)
        y0, y1 = 22 + (min(a, b) - lo) * scale, 22 + (max(a, b) - lo) * scale
        col = NAVY if s["kind"] == "total" else ORANGE if s["kind"] == "manual" else "#c0504d"
        d.add(Rect(i * bw + 8, y0, bw - 16, max(y1 - y0, 1), fillColor=colors.HexColor(col), strokeColor=None))
        d.add(String(i * bw + 8, y1 + 3, _t(_f(s["amount"])), fontSize=6))
        d.add(String(i * bw + 8, 12, _t(s["label"])[:14], fontSize=5.5))
    d.add(Line(0, 22, width, 22, strokeColor=colors.grey, strokeWidth=0.5))
    d.add(String(0, 2, f"Axis starts at {lo:,} EUR m", fontSize=5.5, fillColor=colors.grey))
    return d


def build_pdf(p: dict, sections: list[str], ref: str, viewer: str, ts: str) -> bytes:
    return _pdf(blocks(p, sections, ref, viewer, ts), f"{ref} · {viewer} · {ts}", ref, f"{viewer} · {ts}", "Lineage evidence pack")


def _pdf(content: list[tuple], wm: str, big: str, small: str, title: str) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontSize=8.5, leading=11)
    cell = ParagraphStyle("c", parent=body, fontSize=7, leading=8.5)
    head = ParagraphStyle("hc", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    h1 = ParagraphStyle("h1", parent=ss["Heading2"], textColor=colors.HexColor(NAVY), fontSize=13, keepWithNext=1)

    def decorate(c, doc):
        w, h = A4
        c.saveState()
        c.translate(w / 2, h / 2)
        c.rotate(45)
        c.setFillColor(colors.Color(0.92, 0.92, 0.92))
        c.setFont("Helvetica-Bold", 30)
        c.drawCentredString(0, 0, _t(big))
        c.setFont("Helvetica", 12)
        c.drawCentredString(0, -20, _t(small))
        c.restoreState()
        c.saveState()
        c.setFont("Helvetica", 6.5)
        c.setFillColor(colors.grey)
        c.drawString(15 * mm, 9 * mm, _t(wm))
        c.drawRightString(w - 15 * mm, 9 * mm, f"Page {doc.page}")
        c.drawString(15 * mm, h - 9 * mm, "Lineage Explorer - CONFIDENTIAL")
        c.restoreState()

    story = []
    for i, (_, bl) in enumerate(content):
        if i:
            story.append(PageBreak() if bl[0][1] in ("Sign-off",) else Spacer(1, 8))
        for b in bl:
            if b[0] == "h":
                story.append(Paragraph(escape(_t(b[1])), h1))
            elif b[0] == "p":
                story.append(Paragraph(escape(_t(b[1])), body))
                story.append(Spacer(1, 4))
            elif b[0] == "table":
                rows = [[Paragraph(escape(_t(x)), head) for x in b[1]]] + [[Paragraph(escape(_t(x)), cell) for x in r] for r in b[2]]
                t = Table(rows, repeatRows=1, colWidths=None)
                t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor(NAVY)),
                                       ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey), ("VALIGN", (0, 0), (-1, -1), "TOP")]))
                story += [t, Spacer(1, 6)]
            elif b[0] == "diagram":
                story += [_diagram(b[1]), Spacer(1, 4)]
            elif b[0] == "chart":
                story += [_chart(b[1]), Spacer(1, 4)]
    from reportlab import rl_config

    rl_config.useA85 = 0  # plain streams: text stays greppable for audit checks
    buf = io.BytesIO()
    SimpleDocTemplate(buf, pagesize=A4, pageCompression=0, title=_t(title), author="Lineage Explorer",
                      leftMargin=15 * mm, rightMargin=15 * mm, topMargin=16 * mm, bottomMargin=16 * mm).build(
        story, onFirstPage=decorate, onLaterPages=decorate)
    return buf.getvalue()


# ---------------------------------------------------------------- DOCX
def build_docx(p: dict, sections: list[str], ref: str, viewer: str, ts: str) -> bytes:
    from docx import Document

    doc = Document()
    wm = f"{ref} · {viewer} · {ts} · CONFIDENTIAL"
    sec = doc.sections[0]
    sec.header.paragraphs[0].text = wm  # repeated on every page
    sec.footer.paragraphs[0].text = f"Lineage Explorer evidence pack {ref}"
    for _, bl in blocks(p, sections, ref, viewer, ts):
        for b in bl:
            if b[0] == "h":
                doc.add_heading(b[1], level=1 if b[1] == "Lineage evidence pack" else 2)
            elif b[0] == "p":
                doc.add_paragraph(b[1])
            elif b[0] in ("table", "diagram", "chart"):
                header, rows = _as_table(b, p)
                t = doc.add_table(rows=1, cols=len(header), style="Light Grid Accent 1")
                for i, x in enumerate(header):
                    t.rows[0].cells[i].text = str(x)
                for r in rows:
                    cells = t.add_row().cells
                    for i, x in enumerate(r):
                        cells[i].text = str(x)
                doc.add_paragraph()
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def _as_table(b: tuple, p: dict) -> tuple[list, list]:
    if b[0] == "table":
        return b[1], b[2]
    if b[0] == "diagram":  # renderPM is unavailable, so the diagram is a table of hops
        nodes = {n["uid"]: n["label"] for n in b[1]["nodes"]}
        return ["Hop", "From", "To"], [[e.get("hop", ""), nodes[e["src"]], nodes[e["dst"]]] for e in b[1]["edges"]]
    return ["Step", "Amount (EUR m)"], [[s["label"], _f(s["amount"])] for s in b[1]]


# ---------------------------------------------------------------- other documents
def impact_report_pdf(element: dict, w: dict, haircut: float, incident: str | None, viewer: str, ts: str) -> bytes:
    inc = incident or "INC-[NUMBER]"
    rows = [[r["label"], r["ref"], _f(r["reported"]), _f(r["from_element"]), _f(r["estimated"]),
             ("+" if r["change"] > 0 else "") + _f(r["change"]), f"{r['pct_of_cell']:.2f}%", r["threshold"]] for r in w["rows"]]
    rt = w["ratio"]
    bl = [("h", f"Impact report · {element['name']}"),
          ("p", f"Incident {inc} · haircut {haircut:g}% · generated by {viewer} at {ts}."),
          ("table", ["Impacted cell", "Cell", "Reported", "From element", "Estimated", "Change", "% of cell", "Threshold"], rows)]
    if rt:
        bl.append(("p", f"CET1 ratio (C 03.00): {rt['reported_pct']:.2f}% to {rt['estimated_pct']:.2f}% "
                        f"({rt['change_bps']:+.1f} bps; resubmission threshold {rt['threshold_bps']} bps)."))
    bl += [("h", w["decision"]["title"]), ("p", w["decision"]["text"]), ("p", w["method_note"]),
           ("table", ["Critical data element", "Pilot cells"], [[c["field"], f"{c['cells']} of {c['of']}"] for c in w["cde_footprint"]])]
    return _pdf([("impact", bl)], f"Impact report · {inc} · {viewer} · {ts}", "IMPACT ESTIMATE", f"{viewer} · {ts}", "Impact report")


def adjustment_evidence_pdf(adj: dict, viewer: str, ts: str) -> bytes:
    bl = [("h", "Licence register extract (placeholder)"),
          ("p", f"Evidence attached to {adj['id']}: banking licence confirmed for counterparty [CPTY-•••4821]. "
                "This is an illustrative placeholder generated by the demo; the real extract is held in the EUC workbook."),
          ("table", ["Field", "Value"], [["Adjustment", adj["id"]], ["Amount (EUR m)", _f(adj["amount"])],
                                          ["Maker", adj["maker"]], ["Checker", adj["checker"]], ["Source", adj["source"]]])]
    return _pdf([("evidence", bl)], f"{adj['id']} · {viewer} · {ts}", "PLACEHOLDER", f"{viewer} · {ts}", "Licence register extract")
